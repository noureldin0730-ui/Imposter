class Victim {
  final String name;
  final int age;
  final String job;
  final String description;
  const Victim({
    required this.name,
    required this.age,
    required this.job,
    required this.description,
  });
}

class Suspect {
  final String name;
  final int age;
  final String relation;
  final String story;
  final String alibi;
  const Suspect({
    required this.name,
    required this.age,
    required this.relation,
    required this.story,
    required this.alibi,
  });
}

class Evidence {
  final String title;
  final String detail;
  const Evidence({required this.title, required this.detail});
}

class Testimony {
  final String speaker;
  final String text;
  const Testimony({required this.speaker, required this.text});
}

class Case {
