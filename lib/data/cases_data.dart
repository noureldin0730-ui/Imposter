  final String killer;
  final String solution;
  const Case({
    required this.id,
    required this.title,
    required this.location,
    required this.time,
    required this.crimeScene,
    required this.victim,
    required this.suspects,
    required this.evidences,
    required this.testimonies,
    required this.killer,
    required this.solution,
  });
}

